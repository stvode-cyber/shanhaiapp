#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
从 Kotlin 源码抽取《山海妖志》静态数据层（妖池 + 技能库），生成 prototype/data.js。
直接解析 shared 源码，保证与 Kotlin 真值零漂移（不手工转录）。
生成文件同时支持 browser(window.SH_DATA) 与 Node(module.exports)。
"""
import re
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "shared", "src", "commonMain", "kotlin", "com", "shanhai", "core")
MONSTER_POOL = os.path.join(ROOT, "data", "MonsterPool.kt")
SKILL_LIB = os.path.join(ROOT, "data", "SkillLibrary.kt")
EQUIP_LIB = os.path.join(ROOT, "data", "EquipmentLibrary.kt")

# ---------- 解析技能库 ----------
def parse_skills(path):
    text = open(path, encoding="utf-8").read()
    skills = []
    # Skill("id","name",SkillType.TYPE,Element.EL,power,isDamage,critBonus,"desc")
    pat = re.compile(
        r'Skill\(\s*"([^"]+)"\s*,\s*"([^"]*)"\s*,\s*SkillType\.(\w+)\s*,\s*'
        r'Element\.(\w+)\s*,\s*(\d+)\s*,\s*(true|false)\s*,\s*([\d.]+)\s*,\s*"([^"]*)"'
    )
    for m in pat.finditer(text):
        sid, name, stype, elem, power, isdmg, crit, desc = m.groups()
        skills.append({
            "id": sid, "name": name, "type": stype, "element": elem,
            "power": int(power), "isDamage": (isdmg == "true"),
            "critBonus": float(crit), "desc": desc,
        })
    return skills

# ---------- 解析妖池 ----------
def _extract_blocks(text, opener):
    """按括号平衡抽取所有以 opener 开头（如 'm('）的完整调用块。"""
    blocks = []
    i = 0
    n = len(text)
    while i < n:
        if text.startswith(opener, i):
            depth = 0
            j = i
            while j < n:
                c = text[j]
                if c == '(':
                    depth += 1
                elif c == ')':
                    depth -= 1
                    if depth == 0:
                        blocks.append(text[i:j + 1])
                        i = j + 1
                        break
                j += 1
            else:
                break
        else:
            i += 1
    return blocks

def parse_monsters(path):
    text = open(path, encoding="utf-8").read()
    monsters = []
    for block in _extract_blocks(text, "m("):
        # 位置参数：id,name,category,element,rarity,atk,def,hp,spd
        head = re.match(
            r'm\(\s*"([^"]+)"\s*,\s*"([^"]*)"\s*,\s*MonsterCategory\.(\w+)\s*,\s*'
            r'Element\.(\w+)\s*,\s*Rarity\.(\w+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)',
            block,
        )
        if not head:
            continue
        mid, name, cat, elem, rar, atk, dfn, hp, spd = head.groups()
        # 技能列表
        lm = re.search(r'listOf\(([^)]*)\)', block)
        skill_ids = []
        if lm:
            skill_ids = re.findall(r'"([^"]+)"', lm.group(1))
        # 命名参数
        evolve_from = re.search(r'evolveFrom\s*=\s*"([^"]+)"', block)
        evolve_to = re.search(r'evolveTo\s*=\s*"([^"]+)"', block)
        festival = re.search(r'isFestival\s*=\s*true', block)
        clan = re.search(r'clan\s*=\s*"([^"]+)"', block)
        desc = re.search(r'desc\s*=\s*"([^"]*)"', block)
        monsters.append({
            "id": mid, "name": name, "category": cat, "element": elem, "rarity": rar,
            "baseAtk": int(atk), "baseDef": int(dfn), "baseHp": int(hp), "baseSpd": int(spd),
            "skillIds": skill_ids,
            "evolveFrom": evolve_from.group(1) if evolve_from else None,
            "evolveTo": evolve_to.group(1) if evolve_to else None,
            "isFestival": bool(festival),
            "clan": clan.group(1) if clan else None,
            "desc": desc.group(1) if desc else "",
        })
    return monsters

# ---------- 解析装备库 ----------
def parse_equipments(path):
    text = open(path, encoding="utf-8").read()
    # EquipDef("id","name",EquipSlot.SLOT,Element.X|null,Rarity.X,atk,def,hp,spd)
    pat = re.compile(
        r'EquipDef\(\s*"([^"]+)"\s*,\s*"([^"]*)"\s*,\s*EquipSlot\.(\w+)\s*,\s*'
        r'(?:Element\.(\w+)|null)\s*,\s*Rarity\.(\w+)\s*,\s*'
        r'(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)'
    )
    equips = []
    for m in pat.finditer(text):
        eid, name, slot, elem, rar, atk, dfn, hp, spd = m.groups()
        equips.append({
            "id": eid, "name": name,
            "slot": slot, "element": (None if elem == "null" else elem),
            "rarity": rar,
            "baseAtk": int(atk), "baseDef": int(dfn), "baseHp": int(hp), "baseSpd": int(spd),
            "bonusPerLevel": 0.12, "maxLevel": 10,
        })
    return equips

def main():
    skills = parse_skills(SKILL_LIB)
    monsters = parse_monsters(MONSTER_POOL)
    equipments = parse_equipments(EQUIP_LIB)
    data = {"skills": skills, "monsters": monsters, "equipments": equipments}
    out = os.path.join(os.path.dirname(__file__), "data.js")
    js = "// AUTO-GENERATED by prototype/gen_data.py — 切勿手工编辑\n"
    js += "// 数据真值直接解析自 shared Kotlin 源码（MonsterPool.kt / SkillLibrary.kt / EquipmentLibrary.kt）\n"
    js += "var SH_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"
    js += "if (typeof module !== 'undefined' && module.exports) { module.exports = SH_DATA; }\n"
    js += "if (typeof window !== 'undefined') { window.SH_DATA = SH_DATA; }\n"
    open(out, "w", encoding="utf-8").write(js)
    print("skills:", len(skills), "monsters:", len(monsters), "equipments:", len(equipments))
    print("written ->", out)

if __name__ == "__main__":
    main()
